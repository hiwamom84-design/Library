let currentLanguage = 'ckb'; // Default language is Kurdish Sorani

function setLanguage(lang) {
  if (translations[lang]) {
    currentLanguage = lang;
    localStorage.setItem('library_lang', lang);
    applyLanguageToDOM();
  }
}

function getTranslation(key) {
  return (translations[currentLanguage] && translations[currentLanguage][key]) || 
         (translations['ckb'] && translations['ckb'][key]) || 
         key;
}

function t(key) {
  return getTranslation(key);
}

function getCurrentLanguage() {
  return currentLanguage;
}

function initLanguage() {
  const saved = localStorage.getItem('library_lang');
  if (saved && translations[saved]) {
    currentLanguage = saved;
  } else {
    currentLanguage = 'ckb'; // Default is Kurdish Sorani
  }
  applyLanguageToDOM();
}

function applyLanguageToDOM() {
  const isRtl = currentLanguage === 'ckb';
  document.documentElement.setAttribute('lang', isRtl ? 'ckb' : 'en');
  document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
  document.body.className = isRtl ? 'lang-ckb rtl' : 'lang-en ltr';

  // Translate all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = t(key);
    }
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      el.placeholder = t(key);
    }
  });

  // Update language switcher button label
  const langToggleBtn = document.getElementById('lang-toggle-btn');
  if (langToggleBtn) {
    langToggleBtn.textContent = currentLanguage === 'ckb' ? 'English (EN)' : 'کوردی سۆرانی (CKB)';
  }
}

